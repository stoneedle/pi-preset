# 安装当前仓库的构建产物和 Windows 登录启动配置。
# 入口：node scripts/run-lifecycle.mjs install
#
# Auto-start model (the Windows counterpart of install.sh's launchd/systemd
# setup, kept admin-free): a HKCU Run-key entry launches pi-web-start.vbs at
# login, which runs pi-web-start.ps1 without a console window; the .ps1 loads
# ~/.config/pi-web/env (token, proxy, service settings) and starts the binary hidden.
# Requires the pi CLI plus a bash for pi's shell tool (Git Bash is enough —
# see pi's docs/windows.md).

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

if ($env:PI_WEB_INSTALL_DIR) {
  $InstallDir = $env:PI_WEB_INSTALL_DIR
} else {
  # No sudo-writable /usr/local/bin equivalent on Windows; the pi agent bin
  # dir works for both npm-lifecycle and standalone installs without elevation.
  $InstallDir = Join-Path $HOME '.pi\agent\bin'
}
$Binary = Join-Path $InstallDir 'pi-web.exe'
$ConfigDir = Join-Path $HOME '.config\pi-web'
$EnvFile = Join-Path $ConfigDir 'env'
$LauncherPs1 = Join-Path $ConfigDir 'pi-web-start.ps1'
$LauncherVbs = Join-Path $ConfigDir 'pi-web-start.vbs'
$RunKey = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run'

function Info($msg) { Write-Host "-> $msg" }
function Warn($msg) { Write-Host "!  $msg" -ForegroundColor Yellow }

function Stop-PiWeb {
  # 原位更新保留旧进程，由调用方通过现有启动器重启。
  Get-Process -Name 'pi-web' -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
  Start-Sleep -Seconds 1
}

function Install-Binary($src, $tag) {
  New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
  # Retired images remain locked until their process exits. Give each swap its
  # own path so another source update can complete while an older image runs.
  Get-ChildItem -LiteralPath $InstallDir -Filter 'pi-web.exe.old*' -ErrorAction SilentlyContinue |
    ForEach-Object { Remove-Item -LiteralPath $_.FullName -Force -ErrorAction SilentlyContinue }
  $old = "$Binary.old.$([guid]::NewGuid().ToString('N'))"
  if (Test-Path -LiteralPath $Binary) { Move-Item -LiteralPath $Binary -Destination $old -Force }
  Copy-Item -LiteralPath $src -Destination $Binary -Force
  Remove-Item -LiteralPath $old -Force -ErrorAction SilentlyContinue

  Info "pi-web $tag installed to $Binary"
}

function Set-EnvFileVar($file, $key, $value) {
  $lines = @()
  if (Test-Path -LiteralPath $file) { $lines = @(Get-Content -LiteralPath $file -Encoding UTF8) }
  $found = $false
  $lines = @($lines | ForEach-Object {
    if ($_ -match ('^' + [regex]::Escape($key) + '=')) { $found = $true; "$key=$value" } else { $_ }
  })
  if (-not $found) { $lines += "$key=$value" }
  [IO.File]::WriteAllLines($file, [string[]]$lines, [Text.UTF8Encoding]::new($false))
}

function Initialize-EnvFile {
  New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null
  if (-not (Test-Path -LiteralPath $EnvFile)) { New-Item -ItemType File -Path $EnvFile | Out-Null }

  $hasToken = Select-String -LiteralPath $EnvFile -Pattern '^PI_WEB_TOKEN=' -Quiet
  if (-not $env:PI_WEB_TOKEN -and -not $hasToken) {
    $bytes = New-Object byte[] 16
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $token = -join ($bytes | ForEach-Object { $_.ToString('x2') })
    Set-EnvFileVar $EnvFile 'PI_WEB_TOKEN' $token
    Info "Generated PI_WEB_TOKEN in $EnvFile"
    Warn "Use this token when opening pi-web from another device: $token"
  }

  # Persist PI_CODING_AGENT_DIR so auto-started pi-web finds the right sessions.
  if ($env:PI_CODING_AGENT_DIR) { Set-EnvFileVar $EnvFile 'PI_CODING_AGENT_DIR' $env:PI_CODING_AGENT_DIR }

  # Windows owns toolchain discovery; never persist a build or shell snapshot.
  $lines = @(Get-Content -LiteralPath $EnvFile -Encoding UTF8 | Where-Object {
    $_ -notmatch '^\s*(PATH|PSModulePath)\s*='
  })
  [IO.File]::WriteAllLines($EnvFile, [string[]]$lines, [Text.UTF8Encoding]::new($false))
}

function Initialize-Autostart {
  New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null

  $ps1 = @'
# Generated by pi-web install.ps1. Windows owns shared toolchain configuration.
$ErrorActionPreference = 'Stop'
foreach ($scope in 'Machine', 'User') {
  foreach ($entry in [Environment]::GetEnvironmentVariables($scope).GetEnumerator()) {
    if ($entry.Key -in 'Path', 'PSModulePath') { continue }
    Set-Item -LiteralPath ('Env:' + $entry.Key) -Value ([Environment]::ExpandEnvironmentVariables($entry.Value))
  }
}
$env:Path = [Environment]::ExpandEnvironmentVariables(
  [Environment]::GetEnvironmentVariable('Path', 'Machine') + ';' +
  [Environment]::GetEnvironmentVariable('Path', 'User'))
$envFile = Join-Path $PSScriptRoot 'env'
if (Test-Path -LiteralPath $envFile) {
  foreach ($line in Get-Content -LiteralPath $envFile -Encoding UTF8) {
    if ($line -match '^\s*#' -or $line -notmatch '=') { continue }
    $name, $value = $line -split '=', 2
    $name = $name.Trim()
    if ($name -in 'Path', 'PSModulePath') { continue }
    Set-Item -LiteralPath ('Env:' + $name) -Value $value
  }
}
Start-Process -FilePath '__PI_WEB_BINARY__' -WorkingDirectory '__PI_WEB_HOME__' -WindowStyle Hidden -RedirectStandardOutput (Join-Path $PSScriptRoot 'stdout.log') -RedirectStandardError (Join-Path $PSScriptRoot 'stderr.log')
'@
  $ps1 = $ps1.Replace('__PI_WEB_BINARY__', $Binary.Replace("'", "''")).Replace('__PI_WEB_HOME__', $HOME.Replace("'", "''"))
  # Windows PowerShell 5.1 requires a BOM for non-ASCII paths, with LF or CRLF.
  [IO.File]::WriteAllText($LauncherPs1, $ps1, [Text.UTF8Encoding]::new($true))

  # Let Windows PowerShell initialize its own modules, not inherit another host.
  $vbs = 'Set shell = CreateObject("WScript.Shell")' + "`r`n" +
    'shell.Environment("Process").Remove "PSModulePath"' + "`r`n" +
    'shell.Run "powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File ""' + $LauncherPs1 + '""", 0, False'
  # Windows Script Host supports UTF-16 for paths outside the system code page.
  [IO.File]::WriteAllText($LauncherVbs, $vbs, [Text.Encoding]::Unicode)

  Set-ItemProperty -Path $RunKey -Name 'pi-web' -Value ('wscript.exe "' + $LauncherVbs + '"')
  Info 'Windows auto-start configured (Run key + hidden launcher)'
}

function Start-PiWeb {
  Start-Process -FilePath 'wscript.exe' -ArgumentList ('"' + $LauncherVbs + '"')
}

function Main {
  Write-Host ''
  Info 'pi-web installer (Windows)'
  Write-Host ''

  $sourceBinary = $env:PI_WEB_SOURCE_BINARY
  if (-not $sourceBinary) { $sourceBinary = Join-Path $PSScriptRoot 'pi-web.exe' }
  if (-not (Test-Path -LiteralPath $sourceBinary)) { throw 'Build the fork first with make build BINARY=pi-web.exe, or run node scripts/run-lifecycle.mjs install.' }
  $tag = $env:PI_WEB_SOURCE_VERSION
  if (-not $tag) { $tag = (& $sourceBinary -version).Trim() }

  $inplace = [bool]$env:PI_WEB_INPLACE_UPDATE
  if ((Test-Path -LiteralPath $Binary) -and (Get-FileHash -LiteralPath $Binary -Algorithm SHA256).Hash -eq (Get-FileHash -LiteralPath $sourceBinary -Algorithm SHA256).Hash) {
    if (-not $inplace) {
      Initialize-EnvFile
      Initialize-Autostart
    }
    Info "Already at the current build ($tag)."
    Write-Host ''
    return
  }

  if ((Test-Path -LiteralPath $Binary) -and -not $inplace) { Stop-PiWeb }

  Install-Binary $sourceBinary $tag

  # 原位更新不改环境和启动配置，由调用方重启。
  if ($inplace) {
    Info "Binary updated to $tag; pi-web will restart to apply it."
    Write-Host ''
    return
  }

  Initialize-EnvFile
  Initialize-Autostart

  Info 'pi-web will listen on localhost; if Tailscale is running, it will publish HTTPS with Tailscale Serve.'
  Start-PiWeb

  Info "Done! pi-web $tag is ready."
  Write-Host ''
}

Main
